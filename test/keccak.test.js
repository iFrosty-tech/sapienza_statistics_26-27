/* Keccak-256 and SHA3-256                                                   */
/* ------------------------------------------------------------------------ */

test('keccak256 of the empty string (EIP-1052)', () => {
  assert.equal(keccak256Hex(new Uint8Array(0)), 'c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470');
  assert.equal(keccak256(new Uint8Array(0)).length, 32);
});

test('keccak256 matches the 256 byte-aligned entries of the Keccak team ShortMsgKAT_256', () => {
  const kat = JSON.parse(fixture('keccak256-shortmsgkat.json'));
  assert.equal(kat.length, 256);
  for (const { bytes, msg, md } of kat) {
    const message = hexToBytes(msg);
    assert.equal(message.length, bytes);
    assert.equal(keccak256Hex(message), md, `${bytes} bytes`);
  }
  for (const n of [135, 136, 137]) assert.ok(kat.some((e) => e.bytes === n), `length ${n} covered`);
});

test('sha3_256 of the empty string (XKCP ShortMsgKAT_SHA3-256, Len = 0)', () => {
  assert.equal(sha3_256Hex(new Uint8Array(0)), 'a7ffc6f8bf1ed76651c14756a061d662f580ff4de43b49fa82d80a4b80f8434a');
});

test('sha3_256 agrees with node:crypto, including the 135/136/137-byte rate boundary and multi-block inputs', () => {
  const rnd = createRandom(202);
  for (const length of [0, 1, 3, 71, 72, 73, 134, 135, 136, 137, 271, 272, 273, 1000, 5000]) {
    const message = rnd.bytes(length);
    assert.equal(sha3_256Hex(message), createHash('sha3-256').update(message).digest('hex'), `length ${length}`);
  }
  assert.equal(sha3_256Hex(utf8Bytes('abc')), createHash('sha3-256').update('abc').digest('hex'));
  assert.equal(sha3_256(new Uint8Array(0)).length, 32);
});

test('Keccak-256 and SHA3-256 differ only by the domain-separation suffix', () => {
  const message = utf8Bytes('abc');
  assert.notEqual(keccak256Hex(message), sha3_256Hex(message));
  assert.equal(bytesToHex(keccakSponge(136, 0x01, message, 32)), keccak256Hex(message));
  assert.equal(bytesToHex(keccakSponge(136, 0x06, message, 32)), sha3_256Hex(message));
});

test('keccakSponge with other parameters: SHA3-512 (rate 72) and SHAKE256 squeezing several blocks', () => {
  const rnd = createRandom(1088);
  for (const length of [0, 71, 72, 73, 500]) {
    const message = rnd.bytes(length);
    assert.equal(
      bytesToHex(keccakSponge(72, 0x06, message, 64)),
      createHash('sha3-512').update(message).digest('hex'),
      `sha3-512, length ${length}`,
    );
    assert.equal(
      bytesToHex(keccakSponge(136, 0x1f, message, 300)),
      createHash('shake256', { outputLength: 300 }).update(message).digest('hex'),
      `shake256, length ${length}`,
    );
  }
});

test('keccakSponge rejects invalid rates and suffixes', () => {
  assert.throws(() => keccakSponge(0, 0x01, new Uint8Array(0), 32), /rate/);
  assert.throws(() => keccakSponge(201, 0x01, new Uint8Array(0), 32), /rate/);
  assert.throws(() => keccakSponge(136, 0x00, new Uint8Array(0), 32), /suffix/);
});
